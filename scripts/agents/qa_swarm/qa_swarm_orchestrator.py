async def run_qa_swarm(
    target_file: str,
    coverage_xml_path: str,
    pr_diff: str = "",
    output_path: str | None = None,
    dry_run: bool = False,
    repo_name: str | None = None,
    base_sha: str | None = None,
) -> dict[str, Any]:
    """
    Run the QA swarm for a single target source file.

    Args:
        target_file:        Repo-relative path to the source file to test.
        coverage_xml_path:  Path to the pytest-cov XML report.
        pr_diff:            Unified diff string (optional).
        output_path:        Where to write the generated test file locally.
        dry_run:            If True, print to stdout instead of writing.
        repo_name:          GitHub repo (e.g. "AI-Gen-AI/C2Pro") for PR mode.
        base_sha:           Base commit SHA for creating branches in PR mode.

    Returns:
        The final QASwarmState dictionary.
    """
    # Read source file
    if not os.path.exists(target_file):
        return {"error": f"Target file not found: {target_file}"}

    source_code = Path(target_file).read_text(encoding="utf-8")

    # Discover existing test files for this module
    module_stem = Path(target_file).stem
    existing_test_files: list[str] = []
    test_dirs = ["apps/api/tests"]
    for test_dir in test_dirs:
        if os.path.isdir(test_dir):
            for p in Path(test_dir).rglob(f"*{module_stem}*.py"):
                existing_test_files.append(str(p))

    initial_state = make_initial_state(
        target_file=target_file,
        source_code=source_code,
        coverage_report_path=coverage_xml_path,
        pr_diff=pr_diff,
        existing_test_files=existing_test_files,
    )
    # Inject orchestrator-level control fields
    initial_state["_output_path"] = output_path  # type: ignore[typeddict-unknown-key]
    initial_state["_dry_run"] = dry_run  # type: ignore[typeddict-unknown-key]
    initial_state["_repo_name"] = repo_name  # type: ignore[typeddict-unknown-key]
    initial_state["_base_sha"] = base_sha  # type: ignore[typeddict-unknown-key]

    app = build_qa_swarm()
    final_state = await app.ainvoke(initial_state)
    return final_state


async def run_qa_swarm_for_pr(
    repo_name: str,
    pr_number: int,
    base_sha: str,
    head_sha: str,
    coverage_xml_path: str,
    dry_run: bool = False,
) -> list[dict[str, Any]]:
    """
    Run the QA swarm for all Python source files touched in a PR that lack tests.

    Reads the PR diff from GitHub API, filters to ``apps/api/src/`` Python files
    that are not test files themselves, then runs ``run_qa_swarm`` for each.

    Args:
        repo_name:          GitHub repo (e.g. "AI-Gen-AI/C2Pro").
        pr_number:          Pull request number.
        base_sha:           Base commit SHA.
        head_sha:           Head commit SHA.
        coverage_xml_path:  Path to the pytest-cov XML report.
        dry_run:            If True, print to stdout instead of writing.

    Returns:
        List of final state dicts, one per processed file.
    """
    try:
        from scripts.agents.base import get_github_client, get_pr, get_pr_diff, get_repo
    except ImportError as exc:
        return [{"error": f"Could not import scripts.agents.base: {exc}"}]

    gh = get_github_client()
    repo = get_repo(gh, repo_name)
    diff = get_pr_diff(repo, base_sha, head_sha)

    # Extract Python source files from diff header lines
    changed_files: list[str] = []
    for line in diff.splitlines():
        if line.startswith("+++ b/"):
            path = line[6:].strip()
            if (
                path.endswith(".py")
                and "apps/api/src/" in path
                and "/test" not in path
                and "conftest" not in path
            ):
                changed_files.append(path)

    if not changed_files:
        print("[QA Swarm] No Python source files found in PR diff.")
        return []

    print(f"[QA Swarm] Processing {len(changed_files)} file(s) from PR #{pr_number}")

    results = []
    for file_path in changed_files:
        if not os.path.exists(file_path):
            print(f"[QA Swarm] Skipping (not found locally): {file_path}")
            continue
        print(f"[QA Swarm] → {file_path}")
        result = await run_qa_swarm(
            target_file=file_path,
            coverage_xml_path=coverage_xml_path,
            pr_diff=diff,
            dry_run=dry_run,
            repo_name=repo_name,
            base_sha=head_sha,
        )
        results.append(result)

    return results


