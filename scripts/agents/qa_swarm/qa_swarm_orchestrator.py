"""
QA Swarm — LangGraph Orchestrator

Builds and executes the multi-agent QA pipeline:

    ContextAnalyzerAgent
          │
    TestGenerationAgent
          │
    QAReviewerAgent ──(issues + iterations < 2)──► TestGenerationAgent (retry)
          │
    commit_or_output ──► END
          │
    [on error] ──────────────────────────────────► END

Usage (CLI):

    # Dry run — print generated test to stdout
    python -m scripts.agents.qa_swarm.qa_swarm_orchestrator \\
      --target-file apps/api/src/coherence/engine_v2.py \\
      --coverage-xml apps/api/coverage.xml \\
      --dry-run

    # Write generated test to a local file
    python -m scripts.agents.qa_swarm.qa_swarm_orchestrator \\
      --target-file apps/api/src/analysis/adapters/graph/workflow.py \\
      --coverage-xml apps/api/coverage.xml \\
      --output-path /tmp/test_workflow_swarm.py

    # PR mode — process all Python files changed in a PR
    python -m scripts.agents.qa_swarm.qa_swarm_orchestrator \\
      --repo AI-Gen-AI/C2Pro \\
      --pr-number 42 \\
      --coverage-xml ci-artifacts/coverage.xml

Environment variables:
    ANTHROPIC_API_KEY   — required for all Claude API calls
    GITHUB_TOKEN        — required for PR mode (reading diffs, creating PRs)
"""

from __future__ import annotations

import argparse
import asyncio
import os
import sys
from pathlib import Path
from typing import Any

from langgraph.graph import END, StateGraph

# ---------------------------------------------------------------------------
# Agent imports
# ---------------------------------------------------------------------------

from .context_analyzer_agent import analyze_context
from .qa_reviewer_agent import review_tests, should_regenerate
from .state import QASwarmState, make_initial_state
from .test_generator_agent import generate_tests

# ---------------------------------------------------------------------------
# commit_or_output node
# ---------------------------------------------------------------------------


async def commit_or_output(state: QASwarmState) -> QASwarmState:
    """
    Final node: write the approved test file to disk or commit it to GitHub.

    In standalone mode (no GITHUB_TOKEN / repo info), writes the file locally.
    In PR mode, uses scripts/agents/base.py utilities to create a branch and
    open a draft PR.
    """
    final_code = state.get("final_test_code", "")
    test_file_path = state.get("test_file_path", "")

    if not final_code:
        return {
            **state,
            "committed": False,
        }

    output_path: str | None = state.get("_output_path")  # type: ignore[assignment]
    dry_run: bool = state.get("_dry_run", False)  # type: ignore[assignment]

    if dry_run:
        print("=" * 80)
        print(f"[DRY RUN] Generated test file: {test_file_path}")
        print("=" * 80)
        print(final_code)
        print("=" * 80)
        return {**state, "committed": False}

    # Determine write path
    write_path = output_path or test_file_path
    if not write_path:
        return {**state, "committed": False}

    Path(write_path).parent.mkdir(parents=True, exist_ok=True)
    Path(write_path).write_text(final_code, encoding="utf-8")
    print(f"[QA Swarm] Test file written: {write_path}")

    # Optionally commit to GitHub via base.py utilities
    github_token = os.environ.get("GITHUB_TOKEN")
    repo_name: str | None = state.get("_repo_name")  # type: ignore[assignment]
    base_sha: str | None = state.get("_base_sha")  # type: ignore[assignment]

    if github_token and repo_name and base_sha and write_path:
        try:
            from scripts.agents.base import (
                create_branch_and_commit,
                get_github_client,
                get_repo,
                open_draft_pr,
            )

            gh = get_github_client()
            repo = get_repo(gh, repo_name)
            branch_name = f"qa-swarm/auto-tests-{Path(write_path).stem}"

            create_branch_and_commit(
                repo=repo,
                base_sha=base_sha,
                branch_name=branch_name,
                file_path=write_path,
                new_content=final_code,
                commit_message=(
                    f"test(qa-swarm): auto-generate tests for "
                    f"{state.get('target_file', 'unknown')}"
                ),
            )

            target = state.get("target_file", "unknown")
            pr = open_draft_pr(
                repo=repo,
                head_branch=branch_name,
                base_branch="develop",
                title=f"[QA Swarm] Auto-generated tests for `{Path(target).name}`",
                body=(
                    f"## Auto-generated by QA Swarm\n\n"
                    f"**Target file:** `{target}`\n\n"
                    f"**Generated by:** ContextAnalyzerAgent → TestGenerationAgent → QAReviewerAgent\n\n"
                    f"**Scenarios covered:** {len(state.get('test_scenarios', []))}\n\n"
                    f"**Review iterations:** {state.get('review_iterations', 0)}\n\n"
                    f"> ⚠️ This is an auto-generated draft. A human must review before merging.\n"
                ),
            )
            print(f"[QA Swarm] Draft PR created: {pr.html_url}")
        except Exception as exc:
            print(f"[QA Swarm] GitHub commit failed (local file still written): {exc}")

    return {**state, "committed": True}


# ---------------------------------------------------------------------------
# Graph builder
# ---------------------------------------------------------------------------


def build_qa_swarm() -> Any:
    """
    Construct the compiled LangGraph StateGraph for the QA swarm.

    Graph topology:
        context_analyzer → test_generator → qa_reviewer
          └─ (regenerate) ─────────────────►┘
          └─ (approve)    → commit_or_output → END
          └─ (fail)       → END

    The ``error`` field in state acts as a global abort — any node can set it
    and the orchestrator will route to END after the current node completes.
    """
    workflow = StateGraph(QASwarmState)

    workflow.add_node("context_analyzer", analyze_context)
    workflow.add_node("test_generator", generate_tests)
    workflow.add_node("qa_reviewer", review_tests)
    workflow.add_node("commit_or_output", commit_or_output)

    # ── Entry point ──
    workflow.set_entry_point("context_analyzer")

    # ── Error guard: abort on fatal error ──
    def _check_error(state: QASwarmState) -> str:
        if state.get("error"):
            return "end"
        return "continue"

    workflow.add_conditional_edges(
        "context_analyzer",
        _check_error,
        {"end": END, "continue": "test_generator"},
    )

    workflow.add_conditional_edges(
        "test_generator",
        _check_error,
        {"end": END, "continue": "qa_reviewer"},
    )

    # ── Review outcome routing ──
    workflow.add_conditional_edges(
        "qa_reviewer",
        should_regenerate,
        {
            "regenerate": "test_generator",
            "approve": "commit_or_output",
            "fail": END,
        },
    )

    workflow.add_edge("commit_or_output", END)

    return workflow.compile()


