def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="qa_swarm_orchestrator",
        description="C2Pro QA Swarm — autonomous test generation pipeline",
    )
    parser.add_argument(
        "--target-file",
        help="Repo-relative path to the source file to analyse",
    )
    parser.add_argument(
        "--coverage-xml",
        required=True,
        help="Path to pytest-cov XML report (coverage.xml)",
    )
    parser.add_argument(
        "--output-path",
        help="Local path to write the generated test file",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print generated test to stdout instead of writing",
    )
    parser.add_argument(
        "--repo",
        help="GitHub repo (e.g. AI-Gen-AI/C2Pro) for PR mode",
    )
    parser.add_argument(
        "--pr-number",
        type=int,
        help="Pull request number for PR mode",
    )
    parser.add_argument(
        "--base-sha",
        help="Base commit SHA (required for PR mode)",
    )
    parser.add_argument(
        "--head-sha",
        help="Head commit SHA (required for PR mode)",
    )
    return parser


async def _async_main(args: argparse.Namespace) -> int:
    if args.pr_number and args.repo:
        # PR mode
        if not args.base_sha or not args.head_sha:
            print("ERROR: --base-sha and --head-sha are required for PR mode", file=sys.stderr)
            return 1
        results = await run_qa_swarm_for_pr(
            repo_name=args.repo,
            pr_number=args.pr_number,
            base_sha=args.base_sha,
            head_sha=args.head_sha,
            coverage_xml_path=args.coverage_xml,
            dry_run=args.dry_run,
        )
        failed = [r for r in results if r.get("error")]
        if failed:
            for r in failed:
                print(f"ERROR: {r['error']}", file=sys.stderr)
            return 1
        return 0

    elif args.target_file:
        # Single file mode
        result = await run_qa_swarm(
            target_file=args.target_file,
            coverage_xml_path=args.coverage_xml,
            output_path=args.output_path,
            dry_run=args.dry_run,
            repo_name=args.repo,
            base_sha=args.base_sha,
        )
        if result.get("error"):
            print(f"ERROR: {result['error']}", file=sys.stderr)
            return 1
        if not result.get("review_passed") and not args.dry_run:
            issues = result.get("review_issues", [])
            print(f"WARNING: QA review did not pass. Issues: {issues}", file=sys.stderr)
            return 2
        return 0

    else:
        print("ERROR: provide --target-file or --pr-number + --repo", file=sys.stderr)
        return 1


def main() -> None:
    parser = _build_arg_parser()
    args = parser.parse_args()
    exit_code = asyncio.run(_async_main(args))
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
