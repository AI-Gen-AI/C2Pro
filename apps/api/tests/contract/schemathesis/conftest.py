"""
Schemathesis contract-test fixtures — TASK-QA-200.

Design:
- Load schema offline from docs/api/openapi.yaml (no live server needed).
- Test via ASGI transport: case.call_asgi(app=contract_app).
- Auth: override get_current_user_id dependency; also inject a valid JWT for
  routes that inspect the header directly.
- Multi-tenant: inject X-Tenant-ID header from a fixed test-tenant UUID.
- Mocked boundaries: C2PRO_AI_MOCK=1, Langsmith/Langchain patched by the
  global isolate_langsmith_and_langchain_sdks autouse fixture (sdk_isolators.py).
- Coverage: session-level hooks write contract-coverage.json on session end.
"""

from __future__ import annotations

import json
import os
from datetime import UTC, datetime, timedelta
from pathlib import Path
from uuid import UUID

import jwt
import pytest
from fastapi import FastAPI

# ---------------------------------------------------------------------------
# Fixed synthetic identities (no DB required for contract tests)
# ---------------------------------------------------------------------------

TENANT_ID: UUID = UUID("c0000001-0000-0000-0000-000000000001")
USER_ID: UUID = UUID("c0000001-0000-0000-0000-000000000002")

_JWT_SECRET: str = os.environ.get(
    "JWT_SECRET_KEY",
    "test-secret-key-min-32-chars-required-for-testing-purposes-only",
)
_JWT_ALGO: str = os.environ.get("JWT_ALGORITHM", "HS256")

# Path to the canonical OpenAPI spec (generated by apps/api/scripts/generate_openapi.py)
SCHEMA_PATH: Path = (
    Path(__file__).resolve().parents[5] / "docs" / "api" / "openapi.yaml"
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def mint_contract_jwt() -> str:
    """Mint a short-lived JWT for the fixed contract-test identity."""
    payload = {
        "sub": str(USER_ID),
        "tenant_id": str(TENANT_ID),
        "email": "contract-test@c2pro.test",
        "role": "admin",
        "exp": datetime.now(UTC) + timedelta(hours=2),
        "iat": datetime.now(UTC),
        "type": "access",
    }
    return jwt.encode(payload, _JWT_SECRET, algorithm=_JWT_ALGO)


def create_contract_app() -> FastAPI:
    """Create the ASGI app with auth dependency overridden for contract tests."""
    os.environ.setdefault("C2PRO_AI_MOCK", "1")

    from src.core.security import get_current_user_id
    from src.main import create_application

    app = create_application()
    # Skip real JWT validation — return the fixed contract-test user ID.
    app.dependency_overrides[get_current_user_id] = lambda: USER_ID
    return app


# ---------------------------------------------------------------------------
# Module-scoped fixtures (one app + token per test file, not per case)
