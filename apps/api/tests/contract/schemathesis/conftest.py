@pytest.fixture(scope="module")
def contract_app() -> FastAPI:
    """ASGI app with auth bypassed for contract tests."""
    return create_contract_app()


@pytest.fixture(scope="module")
def contract_jwt() -> str:
    """JWT for the contract-test user."""
    return mint_contract_jwt()


@pytest.fixture(scope="module")
def contract_headers(contract_jwt: str) -> dict[str, str]:
    """HTTP headers injected into every Schemathesis case."""
    return {
        "Authorization": f"Bearer {contract_jwt}",
        "X-Tenant-ID": str(TENANT_ID),
    }


# ---------------------------------------------------------------------------
# Coverage tracker (session-level pytest hooks)
# ---------------------------------------------------------------------------

_SESSION_COVERED: set[str] = set()
_SESSION_ALL_PATHS: set[str] = set()


def _extract_openapi_paths() -> set[str]:
    """Collect all operation paths from the OpenAPI yaml."""
    if not SCHEMA_PATH.exists():
        return set()
    try:
        import schemathesis

        schema = schemathesis.from_path(str(SCHEMA_PATH), base_url="http://testserver")
        paths: set[str] = set()
        for endpoint in schema.get_all_operations():
            if hasattr(endpoint, "path"):
                paths.add(endpoint.path)
        return paths
    except Exception:
        return set()


def pytest_collection_finish(session: pytest.Session) -> None:
    global _SESSION_ALL_PATHS  # noqa: PLW0603
    _SESSION_ALL_PATHS = _extract_openapi_paths()


def pytest_runtest_logreport(report: pytest.TestReport) -> None:
    """Track paths exercised by Schemathesis cases (encoded in node IDs)."""
    if report.when != "call":
        return
    # Schemathesis encodes path+method in test ID: "test_foo[GET /health/live]"
    node_id = getattr(report, "nodeid", "")
    if "[" in node_id and "]" in node_id:
        fragment = node_id[node_id.index("[") + 1 : node_id.rindex("]")]
        parts = fragment.split(" ", 1)
        if len(parts) == 2:
            _SESSION_COVERED.add(parts[1])


def pytest_sessionfinish(session: pytest.Session, exitstatus: int) -> None:
    """Write contract-coverage.json when the session completes."""
    if not _SESSION_ALL_PATHS and not _SESSION_COVERED:
        return

    covered = _SESSION_COVERED & _SESSION_ALL_PATHS
    uncovered = _SESSION_ALL_PATHS - _SESSION_COVERED
    total = len(_SESSION_ALL_PATHS)
    coverage_pct = round(len(covered) / total * 100, 1) if total > 0 else 0.0

    report = {
        "generated_at": datetime.now(UTC).isoformat(),
        "schema_path": str(SCHEMA_PATH),
        "total_operations": total,
        "covered_operations": len(covered),
        "coverage_pct": coverage_pct,
        "covered": sorted(covered),
        "uncovered": sorted(uncovered),
    }

    out_path = Path(__file__).parents[3] / "contract-coverage.json"
    try:
        out_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    except OSError:
        pass
