"""
state.py — LangGraph State Definitions for Coherence Engine v0.3

Defines the state dataclasses used throughout the coherence evaluation subgraph:
- ClauseWithEmbedding: Clause enriched with embedding vector
- CoherenceGraphState: Full state passed between graph nodes

The state follows LangGraph conventions with TypedDict-style annotations
for reducer functions on list fields.

Location: apps/api/src/coherence/graph/state.py
"""

from __future__ import annotations

import operator
from dataclasses import dataclass, field
from typing import Annotated, Any, Literal

